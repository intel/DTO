static error_t parse_option(int key, char *arg, struct argp_state *state)
{
	struct opts *opts = state->input;

	switch (key) {
	case 'l':
		opts->library = arg;
		break;
	case 'w':
		opts->wait_method = arg;
		break;
	case 'b':
		opts->min_bytes = arg;
		break;
	case 'c':
		opts->cpu_fraction = arg;
		break;
	case 'n':
		opts->numa_aware = arg;
		break;
	case 'q':
		opts->wq_list = arg;
		break;
	case OPT_UMWAIT_DELAY:
		opts->umwait_delay = arg;
		break;
	case OPT_OVERLAPPING_MEMMOVE:
		if (!strcmp(arg, "cpu"))
			opts->overlapping_memmove = "0";
		else if (!strcmp(arg, "dsa"))
			opts->overlapping_memmove = "1";
		else {
			fprintf(stderr,
				"Error: --overlapping-memmove must be 'cpu' or 'dsa'.\n\n");
			argp_usage(state);
		}
		break;
	case OPT_NO_MEMCPY:
		opts->no_memcpy = true;
		break;
	case OPT_NO_MEMMOVE:
		opts->no_memmove = true;
		break;
	case OPT_NO_MEMSET:
		opts->no_memset = true;
		break;
	case OPT_NO_MEMCMP:
		opts->no_memcmp = true;
		break;
	case OPT_NO_CACHE_CONTROL:
		opts->no_cache_control = true;
		break;
	case OPT_NO_AUTO_ADJUST:
		opts->no_auto_adjust = true;
		break;
	case OPT_STDC_ONLY:
		opts->stdc_only = true;
		break;
	case OPT_STATS:
		opts->stats = true;
		break;
	case OPT_LOG_FILE:
		opts->log_file = arg;
		break;
	case OPT_LOG_LEVEL:
		opts->log_level = arg;
		break;
	case OPT_STATS_FILE:
		opts->stats_file = arg;
		break;

	case ARGP_KEY_ARG:
		if (state->arg_num)
			return ARGP_ERR_UNKNOWN;
		if (opts->exename == NULL) {
			/* remaining options will be processed in ARGP_KEY_ARGS */
			return ARGP_ERR_UNKNOWN;
		}
		break;

	case ARGP_KEY_ARGS:
		/* process remaining non-option arguments */
		opts->exename = state->argv[state->next];
		opts->idx = state->next;
		break;

	case ARGP_KEY_NO_ARGS:
	case ARGP_KEY_END:
		if (state->arg_num < 1)
			argp_usage(state);
		break;

	default:
		return ARGP_ERR_UNKNOWN;
	}
	return 0;
}

static void setup_child_environ(struct opts *opts)
{
	const char *lib, *cur;
	char *preload;

	/* value options: only set when explicitly specified */
	if (opts->wait_method)
		setenv("DTO_WAIT_METHOD", opts->wait_method, 1);
	if (opts->min_bytes)
		setenv("DTO_MIN_BYTES", opts->min_bytes, 1);
	if (opts->cpu_fraction)
		setenv("DTO_CPU_SIZE_FRACTION", opts->cpu_fraction, 1);
	if (opts->numa_aware)
		setenv("DTO_IS_NUMA_AWARE", opts->numa_aware, 1);
	if (opts->wq_list)
		setenv("DTO_WQ_LIST", opts->wq_list, 1);
	if (opts->umwait_delay)
		setenv("DTO_UMWAIT_DELAY", opts->umwait_delay, 1);
	if (opts->overlapping_memmove)
		setenv("DTO_OVERLAPPING_MEMMOVE_ACTION", opts->overlapping_memmove, 1);
	if (opts->log_file)
		setenv("DTO_LOG_FILE", opts->log_file, 1);
	if (opts->log_level)
		setenv("DTO_LOG_LEVEL", opts->log_level, 1);
	if (opts->stats_file)
		setenv("DTO_STATS_FILE", opts->stats_file, 1);

	/* flag options: only set when explicitly specified */
	if (opts->no_memcpy)
		setenv("DTO_DSA_MEMCPY", "0", 1);
	if (opts->no_memmove)
		setenv("DTO_DSA_MEMMOVE", "0", 1);
	if (opts->no_memset)
		setenv("DTO_DSA_MEMSET", "0", 1);
	if (opts->no_memcmp)
		setenv("DTO_DSA_MEMCMP", "0", 1);
	if (opts->no_cache_control)
		setenv("DTO_DSA_CC", "0", 1);
	if (opts->no_auto_adjust)
		setenv("DTO_AUTO_ADJUST_KNOBS", "0", 1);
	if (opts->stdc_only)
		setenv("DTO_USESTDC_CALLS", "1", 1);
	if (opts->stats)
		setenv("DTO_COLLECT_STATS", "1", 1);

	/* resolve the libdto path and prepend it to LD_PRELOAD */
	lib = opts->library ? opts->library : getenv("DTO_LIBRARY");
	if (lib == NULL)
		lib = LIBDTO_PATH;

	cur = getenv("LD_PRELOAD");
	if (cur == NULL || *cur == '\0') {
		setenv("LD_PRELOAD", lib, 1);
		return;
	}

	/*
	 * LD_PRELOAD is a colon separated list, so it can be much longer than a
	 * single path.  Allocate the result instead of formatting it into a
	 * fixed size buffer, which would silently drop part of what the caller
	 * had already preloaded.
	 */
	if (asprintf(&preload, "%s:%s", lib, cur) < 0) {
		perror("cannot build LD_PRELOAD");
		exit(EXIT_FAILURE);
	}
	setenv("LD_PRELOAD", preload, 1);
	free(preload);
}

int main(int argc, char *argv[])
{
	struct argp argp = {
		.options = dtoctl_options,
		.parser = parse_option,
		.args_doc = "<program> [<args>...]",
		.doc = "dtoctl -- run a program with DSA Transparent Offload (DTO) preloaded",
	};

	argp_parse(&argp, argc, argv, ARGP_IN_ORDER, NULL, &opts);

	/* pass only the target program and its arguments to execvp() */
	argc -= opts.idx;
	argv += opts.idx;

	setup_child_environ(&opts);

	execvp(opts.exename, argv);
	perror(opts.exename);

	return -1;
}
