/*
 * dtoctl -- a CLI wrapper that runs a program with the DSA Transparent Offload
 * (DTO) library preloaded.  It converts command line options into the DTO_*
 * environment variables and prepends libdto.so to LD_PRELOAD so that users do
 * not need to export the variables or set up LD_PRELOAD manually.
 */

