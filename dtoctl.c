/*
 * dtoctl -- a CLI wrapper that runs a program with the DSA Transparent Offload
 * (DTO) library preloaded.  It converts command line options into the DTO_*
 * environment variables and prepends libdto.so to LD_PRELOAD so that users do
 * not need to export the variables or set up LD_PRELOAD manually.
 */

#ifndef _GNU_SOURCE
#define _GNU_SOURCE     /* for asprintf() */
#endif

#include <argp.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#ifndef LIBDTO_PATH
#define LIBDTO_PATH "/usr/lib64/libdto.so"
#endif

/* argp option keys for the long-only options (no short equivalents) */
enum {
	OPT_UMWAIT_DELAY = 0x100,
	OPT_OVERLAPPING_MEMMOVE,
	OPT_LOG_FILE,
	OPT_LOG_LEVEL,
	OPT_STATS_FILE,
	OPT_NO_MEMCPY,
	OPT_NO_MEMMOVE,
	OPT_NO_MEMSET,
	OPT_NO_MEMCMP,
	OPT_NO_CACHE_CONTROL,
	OPT_NO_AUTO_ADJUST,
	OPT_STDC_ONLY,
	OPT_STATS,
};

struct opts {
	int idx;
	char *exename;

	/* library / preload */
	const char *library;

	/* value options (NULL means "not specified") */
	const char *wait_method;
	const char *min_bytes;
	const char *cpu_fraction;
	const char *numa_aware;
	const char *wq_list;
	const char *umwait_delay;
	const char *overlapping_memmove; /* "0" or "1" after validation */
	const char *log_file;
	const char *log_level;
	const char *stats_file;

	/* flag options (false means "not specified") */
	bool no_memcpy;
	bool no_memmove;
	bool no_memset;
	bool no_memcmp;
	bool no_cache_control;
	bool no_auto_adjust;
	bool stdc_only;
	bool stats;
};

struct opts opts;

