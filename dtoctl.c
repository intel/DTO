/* Parse a decimal integer, rejecting signs, empty strings and trailing garbage. */
static bool parse_ulong(const char *s, unsigned long *val)
{
	char *end;

	if (!isdigit((unsigned char)*s))
		return false;
	errno = 0;
	*val = strtoul(s, &end, 10);
	return errno == 0 && *end == '\0';
}

/* Parse a byte count with an optional K, M or G suffix (powers of 1024). */
static bool parse_size(const char *s, unsigned long *val)
{
	unsigned int shift = 0;
	unsigned long n;
	char *end;

	if (!isdigit((unsigned char)*s))
		return false;
	errno = 0;
	n = strtoul(s, &end, 10);
	if (errno)
		return false;

	switch (*end) {
	case 'k': case 'K':
		shift = 10;
		end++;
		break;
	case 'm': case 'M':
		shift = 20;
		end++;
		break;
	case 'g': case 'G':
		shift = 30;
		end++;
		break;
	}
	if (*end != '\0' || n > (ULONG_MAX >> shift))
		return false;

	*val = n << shift;
	return true;
}

/* Accept an integer in [0, max] for options that select a mode or level. */
static const char *check_level(struct argp_state *state, const char *name,
			       char *arg, unsigned long max)
{
	unsigned long val;

	if (!parse_ulong(arg, &val) || val > max)
		argp_error(state, "invalid %s '%s': must be an integer from 0 to %lu",
			   name, arg, max);
	return arg;
}

static const char *check_path(struct argp_state *state, const char *name, char *arg)
{
	if (*arg == '\0')
		argp_error(state, "--%s needs a non-empty PATH", name);
	return arg;
}

static error_t parse_option(int key, char *arg, struct argp_state *state)
{
	struct opts *opts = state->input;
	unsigned long val = 0;
	char *end, *bytes;
	double frac;
	int i;

	switch (key) {
	case 'l':
		opts->library = check_path(state, "library", arg);
		break;
	case 'i':
		opts->ignore_env = true;
		break;
	case OPT_DRY_RUN:
		opts->dry_run = true;
		break;
	case 'w':
		for (i = 0; wait_methods[i]; i++) {
			if (!strcmp(arg, wait_methods[i]))
				break;
		}
		if (wait_methods[i] == NULL)
			argp_error(state, "invalid wait method '%s': must be yield, "
				   "busypoll, umwait, or tpause", arg);
		opts->wait_method = arg;
		break;
	case 'b':
		if (!parse_size(arg, &val))
			argp_error(state, "invalid minimum size '%s': must be a byte "
				   "count, optionally with a K, M or G suffix", arg);
		/* libdto takes plain bytes, so expand any suffix here */
		if (asprintf(&bytes, "%lu", val) < 0)
			argp_failure(state, EXIT_DTOCTL_FAILURE, errno, "--min-bytes");
		opts->min_bytes = bytes;
		break;
	case 'c':
		errno = 0;
		frac = strtod(arg, &end);
		/* the negated range check also rejects NaN */
		if (end == arg || *end != '\0' || errno || !(frac >= 0.0 && frac < 1.0))
			argp_error(state, "invalid cpu fraction '%s': must be a number "
				   ">= 0.0 and < 1.0", arg);
		opts->cpu_fraction = arg;
		break;
	case 'n':
		opts->numa_aware = check_level(state, "NUMA mode", arg, 2);
		break;
	case 'q':
		if (*arg == '\0' || strlen(arg) >= WQ_LIST_MAX)
			argp_error(state, "invalid WQ list: must be 1 to %d characters",
				   WQ_LIST_MAX - 1);
		opts->wq_list = arg;
		break;
	case OPT_UMWAIT_DELAY:
		/* libdto treats 0 as "use the default", so reject it */
		if (!parse_ulong(arg, &val) || val == 0)
			argp_error(state, "invalid umwait delay '%s': must be a positive "
				   "number of cycles", arg);
		opts->umwait_delay = arg;
		break;
	case OPT_OVERLAPPING_MEMMOVE:
		if (!strcmp(arg, "cpu"))
			opts->overlapping_memmove = "0";
		else if (!strcmp(arg, "dsa"))
			opts->overlapping_memmove = "1";
		else
			argp_error(state, "invalid --overlapping-memmove '%s': must be "
				   "cpu or dsa", arg);
		break;
	case OPT_NO_MEMCPY:
		opts->no_memcpy = true;
		break;
	case OPT_NO_MEMMOVE:
		opts->no_memmove = true;
		break;
	case OPT_NO_MEMSET:
		opts->no_memset = true;
		break;
	case OPT_NO_MEMCMP:
		opts->no_memcmp = true;
		break;
	case OPT_NO_CACHE_CONTROL:
		opts->no_cache_control = true;
		break;
	case OPT_NO_AUTO_ADJUST:
		opts->no_auto_adjust = true;
		break;
	case OPT_STDC_ONLY:
		opts->stdc_only = true;
		break;
	case OPT_STATS:
		opts->stats = true;
		break;
	case OPT_LOG_FILE:
		opts->log_file = check_path(state, "log-file", arg);
		break;
	case OPT_LOG_LEVEL:
		opts->log_level = check_level(state, "log level", arg, 2);
		break;
	case OPT_STATS_FILE:
		opts->stats_file = check_path(state, "stats-file", arg);
		break;
	case OPT_STATS_FORMAT:
		if (strcmp(arg, "text") && strcmp(arg, "json"))
			argp_error(state, "invalid stats format '%s': must be text or json",
				   arg);
		opts->stats_format = arg;
		break;
	case OPT_STATS_INTERVAL:
		if (!parse_ulong(arg, &val) || val == 0 || val > INT_MAX)
			argp_error(state, "invalid stats interval '%s': must be a positive "
				   "number of milliseconds", arg);
		opts->stats_interval = arg;
		break;
	case OPT_STATS_RUN:
		opts->stats_run = true;
		opts->stats_dir = arg ? check_path(state, "stats-run", arg) : NULL;
		/* libdto would expand a %p in the stats file names */
		if (arg && strstr(arg, "%p"))
			argp_error(state, "--stats-run directory '%s' cannot contain '%%p'",
				   arg);
		break;
	case OPT_REPEAT:
		if (!parse_ulong(arg, &val) || val == 0 || val > REPEAT_MAX)
			argp_error(state, "invalid repeat count '%s': must be from 1 to %d",
				   arg, REPEAT_MAX);
		opts->repeat = val;
		break;
	case OPT_PERF:
		opts->perf = arg ? check_path(state, "perf", arg) : "perf";
		break;

	case ARGP_KEY_ARG:
		/* leave the program and its arguments to ARGP_KEY_ARGS */
		return ARGP_ERR_UNKNOWN;

	case ARGP_KEY_ARGS:
		/* process remaining non-option arguments */
		opts->exename = state->argv[state->next];
		opts->idx = state->next;
		break;

	case ARGP_KEY_END:
		/* --dry-run can show the environment without a program */
		if (opts->exename == NULL && (!opts->dry_run || opts->stats_run))
			argp_usage(state);
		if ((opts->repeat || opts->perf) && !opts->stats_run)
			argp_error(state, "--repeat and --perf need --stats-run");
		/* a stats run chooses these itself, for each run */
		if (opts->stats_run && opts->stdc_only)
			argp_error(state, "--stats-run runs the program CPU-only itself; "
				   "drop --stdc-only");
		if (opts->stats_run && (opts->stats_file || opts->stats_format))
			argp_error(state, "--stats-run writes JSON stats to its own "
				   "directory; drop --stats-file and --stats-format");
		break;

	default:
		return ARGP_ERR_UNKNOWN;
	}
	return 0;
}

/* DTO_* variables set from options, in the order they were set, for --dry-run */
static const char *option_vars[32];
static int nr_option_vars;

static void set_option_var(const char *name, const char *value)
{
	if (setenv(name, value, 1)) {
		perror("dtoctl: setenv");
		exit(EXIT_DTOCTL_FAILURE);
	}
	option_vars[nr_option_vars++] = name;
}

static bool is_option_var(const char *name, int len)
{
	for (int i = 0; i < nr_option_vars; i++) {
		if ((int)strlen(option_vars[i]) == len && !strncmp(option_vars[i], name, len))
			return true;
	}
	return false;
}

/* Unset every DTO_* variable inherited from the caller (--ignore-env). */
static void clear_dto_environ(void)
{
	char **env, *eq, *name;
	bool found;

	/* unsetenv() reshuffles environ, so rescan it after every removal */
	do {
		found = false;
		for (env = environ; *env; env++) {
			eq = strchr(*env, '=');
			if (strncmp(*env, "DTO_", 4) || eq == NULL)
				continue;
			name = strndup(*env, eq - *env);
			if (name == NULL || unsetenv(name)) {
				perror("dtoctl: unsetenv");
				exit(EXIT_DTOCTL_FAILURE);
			}
			free(name);
			found = true;
			break;
		}
	} while (found);
}

static void setup_dto_environ(struct opts *opts)
{
	/* value options: only set when explicitly specified */
	if (opts->wait_method)
		set_option_var("DTO_WAIT_METHOD", opts->wait_method);
	if (opts->min_bytes)
		set_option_var("DTO_MIN_BYTES", opts->min_bytes);
	if (opts->cpu_fraction)
		set_option_var("DTO_CPU_SIZE_FRACTION", opts->cpu_fraction);
	if (opts->numa_aware)
		set_option_var("DTO_IS_NUMA_AWARE", opts->numa_aware);
	if (opts->wq_list)
		set_option_var("DTO_WQ_LIST", opts->wq_list);
	if (opts->umwait_delay)
		set_option_var("DTO_UMWAIT_DELAY", opts->umwait_delay);
	if (opts->overlapping_memmove)
		set_option_var("DTO_OVERLAPPING_MEMMOVE_ACTION", opts->overlapping_memmove);
	if (opts->log_file)
		set_option_var("DTO_LOG_FILE", opts->log_file);
	if (opts->log_level)
		set_option_var("DTO_LOG_LEVEL", opts->log_level);
	if (opts->stats_file)
		set_option_var("DTO_STATS_FILE", opts->stats_file);
	if (opts->stats_format)
		set_option_var("DTO_STATS_FORMAT", opts->stats_format);
	if (opts->stats_run)
		set_option_var("DTO_STATS_FORMAT", "json");
	if (opts->stats_interval)
		set_option_var("DTO_STATS_INTERVAL_MS", opts->stats_interval);

	/* flag options: only set when explicitly specified */
	if (opts->no_memcpy)
		set_option_var("DTO_DSA_MEMCPY", "0");
	if (opts->no_memmove)
		set_option_var("DTO_DSA_MEMMOVE", "0");
	if (opts->no_memset)
		set_option_var("DTO_DSA_MEMSET", "0");
	if (opts->no_memcmp)
		set_option_var("DTO_DSA_MEMCMP", "0");
	if (opts->no_cache_control)
		set_option_var("DTO_DSA_CC", "0");
	if (opts->no_auto_adjust)
		set_option_var("DTO_AUTO_ADJUST_KNOBS", "0");
	if (opts->stdc_only)
		set_option_var("DTO_USESTDC_CALLS", "1");
	/* libdto ignores the other DTO_STATS_* unless stats are collected */
	if (opts->stats || opts->stats_file || opts->stats_format ||
	    opts->stats_interval || opts->stats_run)
		set_option_var("DTO_COLLECT_STATS", "1");
}

/* The libdto.so installed relative to this dtoctl, if there is one. */
static char *installed_library(void)
{
#ifdef LIBDTO_REL_PATH
	char exe[PATH_MAX], *path, *real;
	ssize_t len;

	len = readlink("/proc/self/exe", exe, sizeof(exe) - 1);
	if (len < 0)
		return NULL;
	exe[len] = '\0';

	if (asprintf(&path, "%s/%s", dirname(exe), LIBDTO_REL_PATH) < 0)
		return NULL;
	real = realpath(path, NULL);
	free(path);
	if (real && access(real, R_OK)) {
		free(real);
		real = NULL;
	}
	return real;
#else
	return NULL;
#endif
}

/*
 * Resolve the libdto.so to preload: --library, then $DTO_LIBRARY, then the
 * library installed alongside dtoctl, then the compiled-in default.  The
 * result is an absolute path, so it still loads after the program changes
 * directory.  A missing library is an error here; ld.so would only print a
 * warning and run the program without DTO.
 */
static char *resolve_library(struct opts *opts, const char **source)
{
	const char *lib;
	char *path;

	if (opts->library) {
		lib = opts->library;
		*source = "--library";
	} else if ((lib = getenv("DTO_LIBRARY")) && *lib) {
		*source = "DTO_LIBRARY";
	} else if ((path = installed_library())) {
		*source = "installed with dtoctl";
		return path;
	} else {
		lib = LIBDTO_PATH;
		*source = "compiled-in default";
	}

	path = realpath(lib, NULL);
	if (path == NULL || access(path, R_OK)) {
		fprintf(stderr, "dtoctl: cannot use DTO library '%s' (%s): %s\n",
			lib, *source, strerror(errno));
		if (opts->library == NULL)
			fprintf(stderr, "dtoctl: use -l/--library or DTO_LIBRARY to "
				"choose a libdto.so\n");
		exit(EXIT_DTOCTL_FAILURE);
	}

	/* ld.so splits LD_PRELOAD at colons and spaces */
	if (strpbrk(path, ": ")) {
		fprintf(stderr, "dtoctl: DTO library path '%s' cannot be preloaded: "
			"it contains a colon or a space\n", path);
		exit(EXIT_DTOCTL_FAILURE);
	}
	return path;
}

/* true for an LD_PRELOAD entry that names a libdto.so (libdto.so, libdto.so.1, ...) */
static bool is_libdto(const char *entry)
{
	const char *base = strrchr(entry, '/');

	base = base ? base + 1 : entry;
	return !strncmp(base, "libdto.so", strlen("libdto.so"));
}

/*
 * Put lib at the front of LD_PRELOAD.  Other libdto.so entries are dropped:
 * two copies of DTO in one process would both initialize and both open the
 * work queues.
 */
static void setup_preload(const char *lib)
{
	const char *cur = getenv("LD_PRELOAD");
	char *preload, *copy, *entry, *save, *real;

	/*
	 * LD_PRELOAD is a list, so it can be much longer than a single path.
	 * Size the result from the inputs: the kept entries and their colons
	 * never take more than the old value plus one byte.
	 */
	preload = malloc(strlen(lib) + (cur ? strlen(cur) : 0) + 2);
	copy = strdup(cur ? cur : "");
	if (preload == NULL || copy == NULL) {
		perror("dtoctl: cannot build LD_PRELOAD");
		exit(EXIT_DTOCTL_FAILURE);
	}
	strcpy(preload, lib);

	for (entry = strtok_r(copy, ": ", &save); entry;
	     entry = strtok_r(NULL, ": ", &save)) {
		if (is_libdto(entry)) {
			real = realpath(entry, NULL);
			if (real == NULL || strcmp(real, lib))
				fprintf(stderr, "dtoctl: dropping '%s' from LD_PRELOAD "
					"in favor of '%s'\n", entry, lib);
			free(real);
			continue;
		}
		strcat(preload, ":");
		strcat(preload, entry);
	}

	if (setenv("LD_PRELOAD", preload, 1)) {
		perror("dtoctl: setenv");
		exit(EXIT_DTOCTL_FAILURE);
	}
	free(copy);
	free(preload);
}

/* Print s, single-quoted if a shell would otherwise split or expand it. */
static void print_quoted(const char *s)
{
	static const char safe[] = "abcdefghijklmnopqrstuvwxyz"
		"ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_@%+=:,./-";

	if (*s && strspn(s, safe) == strlen(s)) {
		fputs(s, stdout);
		return;
	}

	putchar('\'');
	for (; *s; s++) {
		if (*s == '\'')
			fputs("'\\''", stdout);
		else
			putchar(*s);
	}
	putchar('\'');
}

static void print_var(const char *name, int name_len, const char *value,
		      const char *source)
{
	printf("%.*s=", name_len, name);
	print_quoted(value);
	if (source)
		printf("  # %s", source);
	putchar('\n');
}

/* --dry-run: show the library, the environment and the command to be run */
static void print_dry_run(const char *lib, const char *source, char **argv)
{
	char **env;
	int len;

	printf("library: %s (%s)\n", lib, source);
	print_var("LD_PRELOAD", strlen("LD_PRELOAD"), getenv("LD_PRELOAD"), NULL);

	/* variables from options first, in option order, then inherited ones */
	for (int i = 0; i < nr_option_vars; i++)
		print_var(option_vars[i], strlen(option_vars[i]),
			  getenv(option_vars[i]), "option");
	for (env = environ; *env; env++) {
		len = strcspn(*env, "=");
		if (!strncmp(*env, "DTO_", 4) && (*env)[len] == '=' &&
		    !is_option_var(*env, len))
			print_var(*env, len, *env + len + 1, "inherited");
	}

	if (argv == NULL)
		return;
	fputs("command:", stdout);
	for (int i = 0; argv[i]; i++) {
		putchar(' ');
		print_quoted(argv[i]);
	}
	putchar('\n');
}

/*
 * --stats-run: the program runs with DTO_USESTDC_CALLS set to each of these
 * in turn, with JSON stats going to <dir>/<run>.jsonl.  Runs are named
 * <mode>-<round>, or <mode>-perf for the profiled ones.
 */
struct run_mode {
	const char *name;
	const char *usestdc;
};

static const struct run_mode run_modes[] = {
	{ "cpu", "1" },
	{ "dsa", "0" },
};

#define NR_RUN_MODES	(sizeof(run_modes) / sizeof(run_modes[0]))

/*
 * perf record -q -e cpu-clock -F 999 -o <data> -- <dtoctl> -l <lib> -- <program>
 * cpu-clock samples time on CPU, which is what the report divides up, and
 * needs no hardware counters (so it also works in VMs).
 */
static const char *const perf_record[] = {
	"record", "-q", "-e", "cpu-clock", "-F", "999", "-o",
};

#define PERF_RECORD_ARGS	(sizeof(perf_record) / sizeof(perf_record[0]))
#define PERF_ARGV_OUTPUT	(1 + PERF_RECORD_ARGS)

/* LD_PRELOAD as dtoctl found it, for perf and dto-stats-report */
static char *orig_preload;

/* The caller's LD_PRELOAD without libdto, for perf and the report: they
 * must not be measured, and setup_preload may have kept a libdto the
 * caller had exported. */
static void restore_preload(void)
{
	char *copy = NULL, *preload = NULL, *entry, *save;
	int err;

	if (orig_preload == NULL) {
		err = unsetenv("LD_PRELOAD");
	} else {
		copy = strdup(orig_preload);
		preload = malloc(strlen(orig_preload) + 1);
		if (copy == NULL || preload == NULL) {
			perror("dtoctl: cannot build LD_PRELOAD");
			exit(EXIT_DTOCTL_FAILURE);
		}
		*preload = '\0';
		for (entry = strtok_r(copy, ": ", &save); entry;
		     entry = strtok_r(NULL, ": ", &save)) {
			if (is_libdto(entry))
				continue;
			if (*preload)
				strcat(preload, ":");
			strcat(preload, entry);
		}
		err = *preload ? setenv("LD_PRELOAD", preload, 1) :
				 unsetenv("LD_PRELOAD");
	}
	free(copy);
	free(preload);
	if (err) {
		perror("dtoctl: LD_PRELOAD");
		exit(EXIT_DTOCTL_FAILURE);
	}
}

static char *self_exe(void)
{
	static char exe[PATH_MAX];
	ssize_t len;

	len = readlink("/proc/self/exe", exe, sizeof(exe) - 1);
	if (len < 0) {
		perror("dtoctl: /proc/self/exe");
		exit(EXIT_DTOCTL_FAILURE);
	}
	exe[len] = '\0';
	return exe;
}

/* true if cmd names a program execvp() would run */
static bool executable(const char *cmd)
{
	const char *path = getenv("PATH");
	char *dirs, *dir, *save, *file;
	bool found = false;

	if (strchr(cmd, '/'))
		return access(cmd, X_OK) == 0;
	dirs = strdup(path ? path : "/bin:/usr/bin");
	for (dir = strtok_r(dirs, ":", &save); dir && !found;
	     dir = strtok_r(NULL, ":", &save)) {
		if (asprintf(&file, "%s/%s", *dir ? dir : ".", cmd) < 0)
			break;
		found = access(file, X_OK) == 0;
		free(file);
	}
	free(dirs);
	return found;
}

/* The command for a profiled run; the output file is filled in per run. */
static char **perf_command(const char *perf, const char *lib, char **argv)
{
	int argc = 0, i = 0;
	char **cmd;

	while (argv[argc])
		argc++;
	cmd = calloc(PERF_RECORD_ARGS + argc + 8, sizeof(*cmd));
	if (cmd == NULL) {
		perror("dtoctl");
		exit(EXIT_DTOCTL_FAILURE);
	}
	cmd[i++] = (char *)perf;
	for (size_t j = 0; j < PERF_RECORD_ARGS; j++)
		cmd[i++] = (char *)perf_record[j];
	cmd[i++] = NULL;	/* PERF_ARGV_OUTPUT */
	cmd[i++] = "--";
	/* run dtoctl again under perf, so DTO is preloaded into the program only */
	cmd[i++] = self_exe();
	cmd[i++] = "-l";
	cmd[i++] = (char *)lib;
	cmd[i++] = "--";
	memcpy(cmd + i, argv, argc * sizeof(*cmd));
	return cmd;
}

static void run_name(char *buf, size_t size, const struct run_mode *mode,
		     unsigned long round)
{
	if (round)
		snprintf(buf, size, "%s-%lu", mode->name, round);
	else
		snprintf(buf, size, "%s-perf", mode->name);
}

static void json_string(FILE *f, const char *s)
{
	fputc('"', f);
	for (; *s; s++) {
		unsigned char c = *s;

		if (c == '"' || c == '\\')
			fprintf(f, "\\%c", c);
		else if (c < 0x20)
			fprintf(f, "\\u%04x", c);
		else
			fputc(c, f);
	}
	fputc('"', f);
}

/* the variables each run sets for itself */
static bool is_run_var(const char *name, int len)
{
	return (len == 17 && !strncmp(name, "DTO_USESTDC_CALLS", len)) ||
	       (len == 14 && !strncmp(name, "DTO_STATS_FILE", len));
}

/* First line of runs.jsonl: what was run and how. */
static void write_run_header(FILE *runs, const struct opts *opts, const char *lib,
			     unsigned long repeat, char **argv)
{
	time_t now = time(NULL);
	struct utsname un;
	char start[32], *name;
	bool first = true;
	char **env;
	int len;

	strftime(start, sizeof(start), "%Y-%m-%dT%H:%M:%S%z", localtime(&now));
	if (uname(&un))
		strcpy(un.nodename, "");

	fputs("{\"type\":\"stats_run\",\"dtoctl_version\":", runs);
	json_string(runs, DTO_VERSION);
	fputs(",\"start\":", runs);
	json_string(runs, start);
	fputs(",\"host\":", runs);
	json_string(runs, un.nodename);
	fputs(",\"library\":", runs);
	json_string(runs, lib);
	fprintf(runs, ",\"repeat\":%lu,\"perf\":", repeat);
	if (opts->perf)
		json_string(runs, opts->perf);
	else
		fputs("null", runs);
	fputs(",\"command\":[", runs);
	for (int i = 0; argv[i]; i++) {
		if (i)
			fputc(',', runs);
		json_string(runs, argv[i]);
	}
	fputs("],\"env\":{", runs);
	for (env = environ; *env; env++) {
		len = strcspn(*env, "=");
		if (strncmp(*env, "DTO_", 4) || (*env)[len] != '=' ||
		    is_run_var(*env, len))
			continue;
		name = strndup(*env, len);
		if (name == NULL)
			continue;
		if (!first)
			fputc(',', runs);
		json_string(runs, name);
		fputc(':', runs);
		json_string(runs, *env + len + 1);
		free(name);
		first = false;
	}
	fputs("}}\n", runs);
	fflush(runs);
}

/* Make the --stats-run directory, or check that it is empty; returns its absolute path. */
static char *make_stats_dir(const char *dir)
{
	struct dirent *ent;
	char *path;
	DIR *d;

	/* libdto expands %p in the stats file names; the working directory
	 * may bring one in, so check the full path before creating anything */
	if (dir[0] != '/' && (path = getcwd(NULL, 0)) != NULL) {
		if (strstr(path, "%p")) {
			fprintf(stderr, "dtoctl: stats directory '%s/%s' cannot contain '%%p'\n",
				path, dir);
			exit(EXIT_DTOCTL_FAILURE);
		}
		free(path);
	}
	if (mkdir(dir, 0777) && errno != EEXIST) {
		fprintf(stderr, "dtoctl: cannot create '%s': %s\n", dir, strerror(errno));
		exit(EXIT_DTOCTL_FAILURE);
	}
	/* one run's results only, so the report can't mix two */
	d = opendir(dir);
	if (d == NULL) {
		fprintf(stderr, "dtoctl: cannot open '%s': %s\n", dir, strerror(errno));
		exit(EXIT_DTOCTL_FAILURE);
	}
	while ((ent = readdir(d))) {
		if (strcmp(ent->d_name, ".") && strcmp(ent->d_name, "..")) {
			fprintf(stderr, "dtoctl: '%s' is not empty; give --stats-run a "
				"new directory\n", dir);
			exit(EXIT_DTOCTL_FAILURE);
		}
	}
	closedir(d);

	path = realpath(dir, NULL);
	if (path == NULL) {
		fprintf(stderr, "dtoctl: '%s': %s\n", dir, strerror(errno));
		exit(EXIT_DTOCTL_FAILURE);
	}
	if (strstr(path, "%p")) {
		fprintf(stderr, "dtoctl: stats directory '%s' cannot contain '%%p'\n", path);
		exit(EXIT_DTOCTL_FAILURE);
	}
	return path;
}

static double seconds(struct timeval tv)
{
	return tv.tv_sec + tv.tv_usec / 1e6;
}

/*
 * One run of the program for --stats-run, under perf if perf_argv is set.
 * Appends what happened to runs.jsonl.  Returns 0 if the program succeeded,
 * else the status for dtoctl to exit with.
 */
static int stats_run_one(FILE *runs, const char *dir, const struct run_mode *mode,
			 unsigned long round, char **perf_argv, char **argv)
{
	struct sigaction ign = { .sa_handler = SIG_IGN }, old_int, old_quit;
	char name[32], *stats, *data = NULL;
	struct timespec start, end;
	sigset_t block, saved;
	struct rusage ru;
	int status, err, ret;
	pid_t pid;

	run_name(name, sizeof(name), mode, round);
	if (asprintf(&stats, "%s/%s.jsonl", dir, name) < 0 ||
	    (perf_argv && asprintf(&data, "%s/%s.data", dir, name) < 0)) {
		perror("dtoctl");
		exit(EXIT_DTOCTL_FAILURE);
	}
	if (perf_argv) {
		perf_argv[PERF_ARGV_OUTPUT] = data;
		argv = perf_argv;
	}
	fprintf(stderr, "dtoctl: run %s\n", name);

	/* as system() does: Ctrl-C and Ctrl-\ stop the program, not dtoctl */
	sigemptyset(&block);
	sigaddset(&block, SIGINT);
	sigaddset(&block, SIGQUIT);
	sigprocmask(SIG_BLOCK, &block, &saved);

	clock_gettime(CLOCK_MONOTONIC, &start);
	pid = fork();
	if (pid == 0) {
		sigprocmask(SIG_SETMASK, &saved, NULL);
		if (setenv("DTO_USESTDC_CALLS", mode->usestdc, 1) ||
		    setenv("DTO_STATS_FILE", stats, 1))
			_exit(EXIT_DTOCTL_FAILURE);
		/* under perf, the inner dtoctl sets LD_PRELOAD for the program */
		if (perf_argv)
			restore_preload();
		execvp(argv[0], argv);
		err = errno;
		fprintf(stderr, "dtoctl: cannot run '%s': %s\n", argv[0], strerror(err));
		_exit(err == ENOENT ? EXIT_ENOENT : EXIT_CANNOT_INVOKE);
	}
	if (pid < 0) {
		perror("dtoctl: fork");
		exit(EXIT_DTOCTL_FAILURE);
	}
	sigaction(SIGINT, &ign, &old_int);
	sigaction(SIGQUIT, &ign, &old_quit);
	sigprocmask(SIG_SETMASK, &saved, NULL);

	while (wait4(pid, &status, 0, &ru) < 0) {
		if (errno != EINTR) {
			perror("dtoctl: wait4");
			exit(EXIT_DTOCTL_FAILURE);
		}
	}
	clock_gettime(CLOCK_MONOTONIC, &end);
	sigaction(SIGINT, &old_int, NULL);
	sigaction(SIGQUIT, &old_quit, NULL);

	fprintf(runs, "{\"type\":\"run\",\"name\":\"%s\",\"mode\":\"%s\",\"round\":%lu,"
		"\"profiled\":%s,\"stats\":\"%s.jsonl\",", name, mode->name, round,
		perf_argv ? "true" : "false", name);
	if (perf_argv)
		fprintf(runs, "\"perf_data\":\"%s.data\",", name);
	fprintf(runs, "\"wall_s\":%.6f,\"user_s\":%.6f,\"sys_s\":%.6f,\"maxrss_kb\":%ld,",
		(end.tv_sec - start.tv_sec) + (end.tv_nsec - start.tv_nsec) / 1e9,
		seconds(ru.ru_utime), seconds(ru.ru_stime), ru.ru_maxrss);
	if (WIFEXITED(status)) {
		ret = WEXITSTATUS(status);
		fprintf(runs, "\"exit_status\":%d}\n", ret);
		if (ret)
			fprintf(stderr, "dtoctl: run %s exited with status %d%s\n",
				name, ret, perf_argv ? "" : "; stopping");
	} else {
		ret = 128 + WTERMSIG(status);
		fprintf(runs, "\"signal\":%d}\n", WTERMSIG(status));
		fprintf(stderr, "dtoctl: run %s was killed by signal %d%s\n",
			name, WTERMSIG(status), perf_argv ? "" : "; stopping");
	}
	fflush(runs);
	free(stats);
	free(data);
	return ret;
}

/* Summarize the runs with dto-stats-report, preferring the one beside dtoctl. */
static int run_report(const char *dir)
{
	char *report;

	restore_preload();
	if (asprintf(&report, "%s/dto-stats-report", dirname(self_exe())) >= 0 &&
	    access(report, X_OK) == 0)
		execl(report, report, dir, (char *)NULL);
	execlp("dto-stats-report", "dto-stats-report", dir, (char *)NULL);
	fprintf(stderr, "dtoctl: stats saved in %s; dto-stats-report (not found) "
		"summarizes them\n", dir);
	return 0;
}

static void print_run(const char *dir, const struct run_mode *mode,
		      unsigned long round, char **argv)
{
	char name[32], *stats;

	run_name(name, sizeof(name), mode, round);
	if (asprintf(&stats, "%s/%s.jsonl", dir, name) < 0)
		return;
	printf("run %s: DTO_USESTDC_CALLS=%s DTO_STATS_FILE=", name, mode->usestdc);
	print_quoted(stats);
	for (int i = 0; argv[i]; i++) {
		putchar(' ');
		print_quoted(argv[i]);
	}
	putchar('\n');
	free(stats);
}

/* --stats-run: run the program CPU-only and with DSA, then report. */
static int stats_run(struct opts *opts, const char *lib, const char *source,
		     char **argv)
{
	unsigned long repeat = opts->repeat ? opts->repeat : 1;
	char **perf_argv = NULL, *dir, *data;
	time_t now = time(NULL);
	char name[64];
	FILE *runs;
	size_t m;
	int ret;

	if (opts->stats_dir) {
		dir = (char *)opts->stats_dir;
	} else {
		strftime(name, sizeof(name), "dto-stats-%Y%m%d-%H%M%S", localtime(&now));
		dir = name;
	}
	if (opts->perf)
		perf_argv = perf_command(opts->perf, lib, argv);

	if (opts->dry_run) {
		print_dry_run(lib, source, NULL);
		printf("stats run: %s\n", dir);
		for (unsigned long round = 1; round <= repeat; round++)
			for (m = 0; m < NR_RUN_MODES; m++)
				print_run(dir, &run_modes[m], round, argv);
		for (m = 0; perf_argv && m < NR_RUN_MODES; m++) {
			if (asprintf(&data, "%s/%s-perf.data", dir, run_modes[m].name) < 0)
				break;
			perf_argv[PERF_ARGV_OUTPUT] = data;
			print_run(dir, &run_modes[m], 0, perf_argv);
			free(data);
		}
		printf("report: dto-stats-report ");
		print_quoted(dir);
		putchar('\n');
		return 0;
	}

	/* fail now rather than after the timed runs */
	if (opts->perf && !executable(opts->perf)) {
		fprintf(stderr, "dtoctl: cannot find perf '%s'\n", opts->perf);
		exit(EXIT_DTOCTL_FAILURE);
	}
	dir = make_stats_dir(dir);
	if (asprintf(&data, "%s/runs.jsonl", dir) < 0 ||
	    (runs = fopen(data, "we")) == NULL) {
		fprintf(stderr, "dtoctl: cannot write runs.jsonl in '%s': %s\n", dir,
			strerror(errno));
		exit(EXIT_DTOCTL_FAILURE);
	}
	free(data);
	write_run_header(runs, opts, lib, repeat, argv);

	/* alternate the modes, so drift over time affects both alike */
	for (unsigned long round = 1; round <= repeat; round++) {
		for (m = 0; m < NR_RUN_MODES; m++) {
			ret = stats_run_one(runs, dir, &run_modes[m], round, NULL, argv);
			if (ret)
				return ret;
		}
	}
	/* the profiles are extras: the timed runs are reported without them */
	for (m = 0; perf_argv && m < NR_RUN_MODES; m++) {
		ret = stats_run_one(runs, dir, &run_modes[m], 0, perf_argv, argv);
		if (ret) {
			fprintf(stderr, "dtoctl: reporting the timed runs without a profile\n");
			break;
		}
	}
	fclose(runs);
	fflush(stdout);
	return run_report(dir);
}

int main(int argc, char *argv[])
{
	struct opts opts = {0};
	struct argp argp = {
		.options = dtoctl_options,
		.parser = parse_option,
		.args_doc = "<program> [<args>...]",
		.doc = "dtoctl -- run a program with DSA Transparent Offload (DTO) preloaded"
		       "\vOnly the options given are applied: inherited DTO_* variables "
		       "are kept unless an option overrides them or -i is given.  "
		       "Exit status is the program's own, or 125 if dtoctl fails, "
		       "126 if the program cannot be run, 127 if it is not found.  "
		       "With --stats-run, a run that fails stops the rest, and "
		       "dtoctl exits with its status.",
	};
	const char *source;
	char *lib;
	int err;

	argp_parse(&argp, argc, argv, ARGP_IN_ORDER, NULL, &opts);

	/* clear inherited variables first; this also drops DTO_LIBRARY */
	if (opts.ignore_env)
		clear_dto_environ();
	setup_dto_environ(&opts);

	lib = resolve_library(&opts, &source);
	if (opts.stats_run && getenv("LD_PRELOAD"))
		orig_preload = strdup(getenv("LD_PRELOAD"));
	setup_preload(lib);

	if (opts.stats_run)
		return stats_run(&opts, lib, source, argv + opts.idx);

	if (opts.dry_run) {
		print_dry_run(lib, source, opts.exename ? argv + opts.idx : NULL);
		return 0;
	}

	/* pass only the target program and its arguments to execvp() */
	execvp(opts.exename, argv + opts.idx);
	err = errno;
	fprintf(stderr, "dtoctl: cannot run '%s': %s\n", opts.exename, strerror(err));

	return err == ENOENT ? EXIT_ENOENT : EXIT_CANNOT_INVOKE;
}
